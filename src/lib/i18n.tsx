function mergeInto(target: Record<string, unknown>, overlay: unknown): void {
  if (!overlay || typeof overlay !== "object" || Array.isArray(overlay)) return;
  for (const [key, value] of Object.entries(overlay as Record<string, unknown>)) {
    const current = target[key];
    if (value && typeof value === "object" && !Array.isArray(value)) {
      const nested = current && typeof current === "object" && !Array.isArray(current)
        ? current as Record<string, unknown>
        : {};
      target[key] = nested;
      mergeInto(nested, value);
    } else {
      target[key] = value;
    }
  }
}

