function applyDictionaryOverlays(): void {
  for (const lang of UI_LANGS) {
    const dict = DICTS[lang] as unknown as Record<string, unknown>;
    mergeInto(dict, getMod6Copy(lang));
    mergeInto(dict, getTier3Copy(lang));
    // L'UNIVERS — les neuf lieux (kicker, ambiance, phrase de vide).
    mergeInto(dict, getPlacesCopy(lang));
    // La voix de Jabari (bulles de la mascotte + onboarding).
    mergeInto(dict, getMascotCopy(lang));
    // Le studio d'avatar 3D — absent des 9 dictionnaires non historiques.
    mergeInto(dict, getAvatarCopy(lang));
    // L'export CSV/Anki — absent des 6 dictionnaires non historiques.
    mergeInto(dict, getExportCopy(lang));
    // La PWA (bannière offline, invite d'installation) — module entier,
    // absent des 6 dictionnaires historiques.
    mergeInto(dict, getPwaCopy(lang));
    // La landing publique — module entier, absent partout ailleurs.
    mergeInto(dict, getLandingCopy(lang));
    for (const key of PRUNED_NAV_KEYS) {
      const nav = dict.nav;
      if (nav && typeof nav === "object") {
        delete (nav as Record<string, unknown>)[key];
      }
    }
  }
}

