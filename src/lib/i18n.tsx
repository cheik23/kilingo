const UI_LANG_KEY = "ui_lang"; // persisted UI language

/** Meta de langue avec repli fr — aucune UI ne peut crasher sur une valeur
    localStorage ancienne ou inconnue (métas garanties non-undefined). */
export function uiLangMeta(lang: string): {
  native: string;
  flag: string;
  dir: "ltr" | "rtl";
} {
  const safe = (UI_LANGS as readonly string[]).includes(lang)
    ? (lang as UiLang)
    : "fr";
  return UI_LANG_META[safe];
}

export function loadUiLang(): UiLang {
  try {
    const raw = localStorage.getItem(UI_LANG_KEY);
    if (raw && (UI_LANGS as readonly string[]).includes(raw)) {
      return raw as UiLang;
    }
  } catch {
    /* ignore */
  }
  return "fr";
}

/* ── Cible de traduction « TRADUIRE VERS » (LOT UI 2) ──
   Source unique pour Shadow ET MediaRoom : la cible choisie (parmi les 12
   langues UI) est persistée ici, défaut = langue UI courante. */

const TARGET_LANG_KEY = "shadow.targetLang";

export function loadStoredTargetLang(): UiLang {
  try {
    const raw = localStorage.getItem(TARGET_LANG_KEY);
    if (raw && (UI_LANGS as readonly string[]).includes(raw)) {
      return raw as UiLang;
    }
  } catch {
    /* ignore */
  }
  return loadUiLang();
}

export function storeTargetLang(lang: UiLang): void {
  try {
    localStorage.setItem(TARGET_LANG_KEY, lang);
  } catch {
    /* quota — l'état reste appliqué pour la session */
  }
}

