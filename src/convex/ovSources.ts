export const connectorKeyValidator = v.string();

export function connectorByKey(key: string): Connector | undefined {
  return CONNECTORS.find((c) => c.key === key);
}

/** Un connecteur est vraiment utilisable s'il est branché ET configuré. */
export function connectorReady(c: Connector): boolean {
  return c.implemented && envReady(c.requiresEnv);
}

/** Liste publique des connecteurs + leur état réel. */
export const list = query({
  args: {},
  handler: async () => {
    // Vérification d'honnêteté : le drapeau `implemented` doit correspondre
    // aux connecteurs réellement présents dans `connectors/`.
    const implemented = new Set(specKeys());
    const mismatched = CONNECTORS.filter((c) => c.implemented !== implemented.has(c.key)).map((c) => c.key);

    return {
      connectors: CONNECTORS.map((c) => ({
        ...c,
        missingEnv: c.requiresEnv.filter((name) => !hasEnv(name)),
        ready: connectorReady(c),
        mode:
          c.implemented && connectorReady(c)
            ? c.searchEnabled
              ? "recherche + rayons"
              : "flux (URL) uniquement"
            : c.implemented
              ? "clé manquante"
              : "registre (non branché)",
      })),
      searchEnabled: CONNECTORS.filter((c) => c.searchEnabled && connectorReady(c)).map((c) => c.key),
      /** Signalé tel quel dans l'admin : un drapeau qui dérive est un bug. */
      mismatched,
    };
  },
});

/** Miroir en base : alimente le dashboard admin et le journal d'erreurs. */
export const sync = internalMutation({
  args: { results: v.optional(v.array(v.object({ source: v.string(), error: v.string() }))) },
  handler: async (ctx, args) => {
    const now = Date.now();
    const errors = new Map((args.results ?? []).map((r) => [r.source, r.error]));
    for (const c of CONNECTORS) {
      const existing = await ctx.db
        .query("ovSources")
        .withIndex("by_key", (q) => q.eq("key", c.key))
        .unique();
      const patch = {
        key: c.key,
        name: c.name,
        kind: c.kind,
        category: c.category,
        homepage: c.homepage,
        docsUrl: c.docsUrl,
        license: c.license,
        requiresEnv: c.requiresEnv,
        searchEnabled: c.searchEnabled,
        streamingAllowed: c.allowsRedistribution,
        notes: c.notes,
        active: connectorReady(c),
        lastError: errors.get(c.key),
        lastCheckedAt: now,
      };
      if (existing) await ctx.db.patch(existing._id, patch);
      else await ctx.db.insert("ovSources", patch);
    }
    return { synced: CONNECTORS.length };
  },
});

