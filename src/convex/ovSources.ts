/* ═══════════════════════════════════════════════════════════════════════
   MOOVY — REGISTRE DES CONNECTEURS

   Chaque source externe est décrite ici, et chaque connecteur réellement
   branché a son implémentation dans `connectors/`.

   ⚠️ Une source de MÉTADONNÉES n'est jamais une source de streaming.
      Savoir qu'un film existe ne signifie pas qu'on peut le diffuser.
      `provides` / `allowsRedistribution` / `supportsEmbed` décrivent ce que
      la source autorise, et le Rights Engine tranche ensuite contenu par
      contenu.

   `implemented` est un garde-fou d'honnêteté : il est vérifié au démarrage
   contre `connectors/index.ts`. Une source déclarée mais non branchée est
   affichée « registre » — jamais « active ».
   ═══════════════════════════════════════════════════════════════════════ */

export const connectorValidator = v.object({
  key: v.string(),
  name: v.string(),
  /** metadata : informations seulement. content : œuvres sous licence
   *  exploitable. index : catalogue/agrégateur. dataset : import massif. */
  kind: v.union(v.literal("metadata"), v.literal("content"), v.literal("index"), v.literal("dataset")),
  category: v.union(
    v.literal("film"),
    v.literal("series"),
    v.literal("video"),
    v.literal("music"),
    v.literal("podcast"),
    v.literal("audio"),
    v.literal("book"),
    v.literal("article"),
    v.literal("image"),
    v.literal("social"),
    v.literal("multi"),
  ),
  homepage: v.string(),
  docsUrl: v.optional(v.string()),
  license: v.string(),
  /** Variables d'environnement à renseigner dans l'onglet Keys/API keys. */
  requiresEnv: v.array(v.string()),
  /** Participe à la recherche par mots-clés. */
  searchEnabled: v.boolean(),
  /** Peut alimenter un rayon sans requête (nouveautés / tendances). */
  discoverEnabled: v.boolean(),
  /** Fournit-il un lecteur officiel intégrable (iframe / oEmbed) ? */
  supportsEmbed: v.boolean(),
  /** Fournit-il un extrait promotionnel officiel jouable ? */
  supportsPreview: v.boolean(),
  /** Autorise-t-il la redistribution des œuvres trouvées ? */
  allowsRedistribution: v.boolean(),
  /** Peut-il alimenter le moteur de transcription / traduction ? */
  transcriptionSource: v.boolean(),
  requiresKey: v.boolean(),
  /** Connecteur réellement implémenté dans `connectors/`. */
  implemented: v.boolean(),
  notes: v.string(),
});

